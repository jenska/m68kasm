// operandKindFromEA classifies an EA expression into the broader operand kind categories
// used by instruction form matching, defaulting to OpkEA for generic addressing modes.
func operandKindFromEA(e instructions.EAExpr) instructions.OperandKind {
	if kind, ok := operandKindByEA[e.Kind]; ok {
		return kind
	}
	return instructions.OpkEA
}

func operKindsMatch(expected, actual []instructions.OperandKind) bool {
	if len(expected) != len(actual) {
		return false
	}
	for i := range expected {
		if !operandKindCompatible(expected[i], actual[i]) {
			return false
		}
	}
	return true
}

func operandKindCompatible(expect, actual instructions.OperandKind) bool {
	if expect == actual {
		return true
	}
	if expect == instructions.OpkEA {
		switch actual {
		case instructions.OpkEA, instructions.OpkDn, instructions.OpkAn, instructions.OpkImm, instructions.OpkPredecAn, instructions.OpkPostincAn:
			return true
		}
	}
	// USP is also a MOVEC control register (EAkUSP maps to OpkUSP so
	// MOVE USP,An/An,USP keep working unchanged), so a form requiring
	// OpkCtrlReg must accept an OpkUSP operand too.
	if expect == instructions.OpkCtrlReg && actual == instructions.OpkUSP {
		return true
	}
	return false
}

func itemLocation(it any) (pc uint32, line int, ok bool) {
	switch v := it.(type) {
	case *Instr:
		return v.PC, v.Line, true
	case *DataBytes:
		return v.PC, v.Line, true
	default:
		return 0, 0, false
	}
}
